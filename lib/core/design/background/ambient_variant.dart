  defaultVariant,

  /// Calming subtle lighting for relaxation and gentle review.
  calm,

  /// Deep, undistracted atmosphere for deep work sessions.
  focus,

  /// Crisp, intellective lighting for study, syllabus, and practice.
  learning,

  /// Energetic ambient lighting for planning and tasks.
  productivity,

  /// Rich, balanced lighting for general workspaces.
  workspace,

  /// Dramatic, centered atmospheric depth for login/signup/welcome.
  authentication,
}
